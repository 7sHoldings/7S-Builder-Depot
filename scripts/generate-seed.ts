// Generates supabase/seed.sql from the sample catalog in src/lib/catalog.ts.
// Run with: npm run db:seed-sql
import { writeFileSync } from "node:fs";
import { seedProducts } from "../src/lib/catalog.ts";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replaceAll("'", "''")}'`);
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);

const rows = seedProducts.map((p, i) =>
  [
    q(p.slug),
    q(p.sku),
    q(p.name),
    q(p.category),
    q(p.type),
    p.price.toFixed(2),
    q(p.unit),
    p.sqftPerBox ?? "null",
    q(p.summary),
    q(p.description),
    j(p.specs),
    j(p.colors ?? null),
    j(p.visual),
    p.stock,
    p.featured ? "true" : "false",
    i,
  ].join(", "),
);

const sql = `-- Sample products for 7S Builder Depot (generated by scripts/generate-seed.ts).
-- Prices and stock are SAMPLE values. Safe to re-run: existing products are updated.
insert into public.products
  (slug, sku, name, category, type, price, unit, sqft_per_box, summary, description, specs, colors, visual, stock, featured, sort_order)
values
${rows.map((r) => `  (${r})`).join(",\n")}
on conflict (slug) do update set
  sku = excluded.sku, name = excluded.name, category = excluded.category, type = excluded.type,
  price = excluded.price, unit = excluded.unit, sqft_per_box = excluded.sqft_per_box,
  summary = excluded.summary, description = excluded.description, specs = excluded.specs,
  colors = excluded.colors, visual = excluded.visual, stock = excluded.stock,
  featured = excluded.featured, sort_order = excluded.sort_order;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql with ${seedProducts.length} products`);
