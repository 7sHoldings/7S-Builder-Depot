// Generates supabase/seed.sql from the catalog in src/lib/catalog.ts.
// Run with: npm run db:seed-sql
// The SQL is safe to re-run: products and variants are upserted, and products
// that are no longer in the catalog are hidden (active = false), never deleted.
import { writeFileSync } from "node:fs";
import { seedProducts } from "../src/lib/catalog.ts";

const q = (v: string | null | undefined) => (v == null ? "null" : `'${v.replaceAll("'", "''")}'`);
const j = (v: unknown) => (v == null ? "null" : `${q(JSON.stringify(v))}::jsonb`);
const n = (v: number | null | undefined) => (v == null ? "null" : String(v));
const arr = (v: string[]) => (v.length ? `array[${v.map(q).join(", ")}]::text[]` : "'{}'::text[]");

const productRows = seedProducts.map((p, i) =>
  [
    q(p.slug), q(p.sku), q(p.name), q(p.category), q(p.type), n(p.price), q(p.priceNote), q(p.unit), n(p.sqftPerBox),
    q(p.summary), q(p.description), j(p.specs), j(p.colors ?? null), j(p.visual), arr(p.images), n(p.stock),
    p.featured ? "true" : "false", i,
  ].join(", "),
);

const variantRows = seedProducts.flatMap((p) =>
  p.variants.map((v, i) =>
    [q(v.id), q(p.slug), q(v.sku), q(v.label), n(v.widthIn), n(v.heightIn), q(v.swing), n(v.stock), n(v.price), q(v.image), i].join(", "),
  ),
);

const slugs = seedProducts.map((p) => q(p.slug)).join(", ");
const variantIds = seedProducts.flatMap((p) => p.variants.map((v) => q(v.id))).join(", ");

const sql = `-- 7S Builder Depot catalog (generated by scripts/generate-seed.ts). Safe to re-run.
begin;

insert into public.products
  (slug, sku, name, category, type, price, price_note, unit, sqft_per_box, summary, description,
   specs, colors, visual, images, stock, featured, sort_order, active)
values
${productRows.map((r) => `  (${r}, true)`).join(",\n")}
on conflict (slug) do update set
  sku = excluded.sku, name = excluded.name, category = excluded.category, type = excluded.type,
  price = excluded.price, price_note = excluded.price_note, unit = excluded.unit, sqft_per_box = excluded.sqft_per_box,
  summary = excluded.summary, description = excluded.description, specs = excluded.specs, colors = excluded.colors,
  visual = excluded.visual, images = excluded.images, stock = excluded.stock, featured = excluded.featured,
  sort_order = excluded.sort_order, active = true;

insert into public.product_variants
  (id, product_slug, sku, label, width_in, height_in, swing, stock, price, image, sort_order)
values
${variantRows.map((r) => `  (${r})`).join(",\n")}
on conflict (id) do update set
  product_slug = excluded.product_slug, sku = excluded.sku, label = excluded.label,
  width_in = excluded.width_in, height_in = excluded.height_in, swing = excluded.swing,
  stock = excluded.stock, price = excluded.price, image = excluded.image,
  sort_order = excluded.sort_order, active = true;

-- Hide anything that is no longer in the catalog (keeps order history intact)
update public.products set active = false where slug not in (${slugs});
update public.product_variants set active = false where id not in (${variantIds});

commit;
`;

writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log(`Wrote supabase/seed.sql: ${seedProducts.length} products, ${variantRows.length} variants`);
